def normalize(query: str) -> list[str]:
    """Разбивает запрос на значимые слова (без стоп-слов и мусора)."""
    cleaned = (
        query.lower()
        .replace("?", " ").replace("!", " ").replace(",", " ")
        .replace(".", " ").replace(":", " ").replace(";", " ")
    )
    return [w for w in cleaned.split() if len(w) > 1 and w not in STOPWORDS]


def expand(words: list[str]) -> list[str]:
    """Добавляет к словам запроса синонимы (без дублей, сохраняя порядок)."""
    out: list[str] = []
    seen: set[str] = set()
    for word in words:
        w = word.strip().lower()
        if not w or w in seen:
            continue
        seen.add(w)
        out.append(w)
        for syn in SYNONYMS.get(w, []):
            s = syn.lower()
            if s not in seen:
                seen.add(s)
                out.append(s)
    return out